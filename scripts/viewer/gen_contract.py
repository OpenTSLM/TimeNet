"""Keep frontend API definitions synchronized with the Python backend at build time.

This script reads backend endpoint definitions and Python types to generate:
- ``frontend/schema.json``, which openapi-typescript converts into TypeScript types.
- ``frontend/src/generated/endpoints.ts``, containing endpoint URLs, HTTP methods,
  and mappings to request, response, and query parameter types.

These contracts let TypeScript catch missing request fields, incorrect query parameters,
and nonexistent response fields before runtime. Viewer CI regenerates the files and
checks that the committed output matches the backend. The running viewer does not need
this script.
"""

import json
from pathlib import Path
from typing import Any

from pydantic import TypeAdapter

from timenet.reader.inspection.results import TargetItem, TaskScope
from timenet.viewer.contracts import ENDPOINTS, Endpoint


def _operation(endpoint: Endpoint, schemas: dict) -> dict:
    """Describe one operation, including its path/query parameters and success status.

    Returns:
        The OpenAPI operation object.
    """
    parameters = []
    if endpoint.query is not None:
        query = schemas[endpoint.query.__name__]
        parameters.extend(
            {"name": name, "in": "query", "required": name in query.get("required", []), "schema": field}
            for name, field in query["properties"].items()
        )
    operation: dict[str, object] = {
        "parameters": parameters,
        "responses": {
            str(endpoint.status): {
                "description": "Successful response",
                "content": {
                    "application/json": {"schema": {"$ref": f"#/components/schemas/{endpoint.response.__name__}"}}
                },
            }
        },
    }
    if endpoint.request is not None:
        operation["requestBody"] = {
            "required": True,
            "content": {"application/json": {"schema": {"$ref": f"#/components/schemas/{endpoint.request.__name__}"}}},
        }
    return operation


def main() -> None:
    """Write deterministic schemas, parameters and method-specific endpoint maps."""
    schemas = {}
    models: dict[str, Any] = {"TargetItem": TargetItem, "TaskScope": TaskScope}
    for endpoint in ENDPOINTS:
        for model in (endpoint.request, endpoint.response, endpoint.query):
            if model is not None:
                models[model.__name__] = model
    for name, model in models.items():
        schema = TypeAdapter(model).json_schema(ref_template="#/components/schemas/{model}")  # noqa: RUF027
        schemas.update(schema.pop("$defs", {}))
        schemas[name] = schema
    # Pydantic accepts decimal strings for exact microsecond request bounds.
    for schema in schemas.values():
        for name, field in schema.get("properties", {}).items():
            if name in {"start_us", "end_us"} and any(item.get("type") == "integer" for item in field.get("anyOf", [])):
                field["anyOf"].append({"type": "string", "pattern": "^-?[0-9]+$"})
    paths = {}
    requests, responses, options = [], [], []
    definitions = {}
    for endpoint in ENDPOINTS:
        paths.setdefault(endpoint.path, {})[endpoint.method.lower()] = _operation(endpoint, schemas)
        member = json.dumps(endpoint.key)
        request = "undefined" if endpoint.request is None else f'Schemas["{endpoint.request.__name__}"]'
        requests.append(f"  {member}: {request};")
        responses.append(f'  {member}: Schemas["{endpoint.response.__name__}"];')
        query = "never" if endpoint.query is None else f'Schemas["{endpoint.query.__name__}"]'
        options.append(f"  {member}: {{ signal?: AbortSignal; query?: {query} }};")
        definitions[endpoint.key] = {"path": endpoint.path, "method": endpoint.method}
    frontend = Path(__file__).resolve().parents[2] / "frontend"
    document = {
        "openapi": "3.1.0",
        "info": {"title": "TimeNet viewer", "version": "1"},
        "paths": paths,
        "components": {"schemas": schemas},
    }
    (frontend / "schema.json").write_text(json.dumps(document, indent=2, sort_keys=True) + "\n")
    source = '// Generated by scripts/viewer/gen_contract.py.\nimport type { components } from "./api";\n'
    source += 'type Schemas = components["schemas"];\n'
    for name, members in (("RequestBodies", requests), ("ResponseBodies", responses), ("EndpointOptions", options)):
        source += f"export interface {name} {{\n" + "\n".join(members) + "\n}\n"
    source += "export const endpoints = " + json.dumps(definitions, indent=2) + " as const;\n"
    (frontend / "src/generated/endpoints.ts").write_text(source)


if __name__ == "__main__":
    main()
