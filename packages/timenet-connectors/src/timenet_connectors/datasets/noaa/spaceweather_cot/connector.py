"""The SpaceWeather-CoT connector: NOAA forecaster text paired with the data it explains.

Every record is one issuance of NOAA Space Weather Prediction Center's "Forecast Discussion"
product (issued twice daily, at 0030 and 1230 UTC). The record carries the 24 hours of GOES-16
X-ray flux and OMNI2 hourly solar-wind and geomagnetic values that preceded the issuance. Its
:class:`~timenet.types.AnswerTask` asks a model to write the next 3-day forecast; the forecaster's
own "24 hr Summary" text is the ``rationale`` and the forecaster's own "Forecast" text is the
``targets``. Both are the forecaster's own words, not a caption generated by another model. A
paired "3-Day Forecast" product gives NOAA's own numeric probabilities (expected max Kp, radio
blackout chance, solar radiation storm chance) as :class:`~timenet.types.ScalarPredictionTask`
targets, which is what makes a model-vs-NOAA comparison possible on held-out issuances.

Issuances are fetched individually over HTTP and some are missing from NOAA's archive (observed
gaps, not a connector defect), so :meth:`SpaceWeatherCotConnector.download_async` tolerates a 404
for one issuance and simply excludes it, while still failing loudly on any other HTTP error.
"""

import asyncio
from dataclasses import dataclass
from datetime import UTC, date, datetime, timedelta
from pathlib import Path
import re

import httpx
import numpy as np

from timenet.connectors import BaseConnector
from timenet.dataset import Record, Signal, Source, TimeFDataset
from timenet.dataset.axis import time_offsets_from_datetimes
from timenet.errors import TimeNetConnectorError
from timenet.types import (
    Annotation,
    AnswerTask,
    MissingReason,
    MissingValues,
    ScalarPredictionTask,
    TimeSeriesSpec,
    ureg,
)
from timenet_connectors.download import Artifact, download_files


# --- Pinned sources -----------------------------------------------------------------------------
# A single calendar year of each source keeps this first release simple: one GOES science file and
# one OMNI2 file cover every record's 24-hour lookback window without crossing a year boundary.
# Later versions can add more years and more satellites.
_GOES_XRS_URL = (
    "https://data.ngdc.noaa.gov/platforms/solar-space-observing-satellites/goes/goes16/l2/data/"
    "xrsf-l2-avg1m_science/sci_xrsf-l2-avg1m_g16_y2024_v2-2-2.nc"
)
_GOES_XRS_SHA256 = "f1f3bba66cc64ae3be50417fee3320340b016e76b0e9b3d01486d83e41af9653"
_OMNI2_URL = "https://spdf.gsfc.nasa.gov/pub/data/omni/low_res_omni/omni2_2024.dat"
_OMNI2_SHA256 = "41f3b5891ce3f1220719d5c1ea808f3014f28a1704557d3363eefb5ee7c249b1"
_DISCUSSION_BASE = "https://www.ngdc.noaa.gov/stp/space-weather/swpc-products/daily_reports/discussion"
_FORECAST_BASE = "https://www.ngdc.noaa.gov/stp/space-weather/swpc-products/daily_reports/3day_forecast"

# The date range of this release spans the whole first year of the Forecast Discussion archive
# (the product began in March 2024) and stays inside the single pinned calendar year above.
_START_DATE = date(2024, 3, 1)
_END_DATE = date(2024, 12, 31)
_ISSUANCE_HOURS_UTC = (0, 12)  # 0030 and 1230 UTC, named by their announced hour.
_LOOKBACK = timedelta(hours=24)

_SECTIONS = ("Solar Activity", "Energetic Particle", "Solar Wind", "Geospace")
_SUMMARY_MARKER = re.compile(r"^\s*\.24 hr Summary\.\.\.\s*\n", re.MULTILINE)
_FORECAST_MARKER = re.compile(r"\.Forecast\.\.\.\s*\n")
# NOAA titled the second section "Energetic Particle" in most issues but "Energetic
# Particles" in others (notably early 2024); both spellings name the same section.
_SECTION_HEADER = re.compile(r"^(Solar Activity|Energetic Particles?|Solar Wind|Geospace)\s*$", re.MULTILINE)

_KP_RE = re.compile(r"greatest expected 3 hr Kp for [^\n]*? is ([\d.]+)")
_R1R2_RE = re.compile(r"\nR1-R2\s+(\d+)%")
_S1_RE = re.compile(r"\nS1 or greater\s+(\d+)%")

_FLAGGED = MissingValues(reason=MissingReason.NOT_RECORDED, description="GOES quality flag marked this minute bad")
_FILL = MissingValues(reason=MissingReason.NOT_RECORDED, description="OMNI2 reported its sentinel fill value here")

_XRAY_SPEC = TimeSeriesSpec(
    spec_type="goes_xrsb_flux",
    name="GOES-16 X-ray flux (0.1-0.8 nm)",
    unit_value=ureg.watt / ureg.meter**2,
    missing=_FLAGGED,
)
_BZ_SPEC = TimeSeriesSpec(spec_type="omni_bz_gsm", name="IMF Bz (GSM)", unit_value=ureg.nanotesla, missing=_FILL)
_SPEED_SPEC = TimeSeriesSpec(
    spec_type="omni_solar_wind_speed",
    name="Solar wind speed",
    unit_value=ureg.kilometer / ureg.second,
    missing=_FILL,
)
_DENSITY_SPEC = TimeSeriesSpec(
    spec_type="omni_proton_density", name="Proton density", unit_value=ureg.centimeter**-3, missing=_FILL
)
_KP_SPEC = TimeSeriesSpec(spec_type="omni_kp", name="Planetary Kp index", unit_value=ureg.dimensionless)

_PROMPT = (
    "Given the past 24 hours of GOES X-ray flux and OMNI solar-wind and Kp measurements, "
    "summarize recent solar and geomagnetic activity and forecast the next 3 days."
)


@dataclass(frozen=True)
class _Issuance:
    """One successfully fetched issuance: its two report texts, by local path."""

    issued_at: datetime
    discussion_path: Path
    forecast_path: Path


@dataclass(frozen=True)
class SpaceWeatherRaw:
    """Everything :meth:`SpaceWeatherCotConnector.convert` needs, already on local disk."""

    issuances: tuple[_Issuance, ...]
    xray_path: Path
    omni_path: Path


def _issuance_times() -> list[datetime]:
    """Return every issuance timestamp from :data:`_START_DATE` to :data:`_END_DATE`, inclusive.

    Returns:
        UTC timestamps at 0030 and 1230 for every day in the range, in order.
    """
    times = []
    day = _START_DATE
    while day <= _END_DATE:
        for hour in _ISSUANCE_HOURS_UTC:
            times.append(datetime(day.year, day.month, day.day, hour, 30, tzinfo=UTC))
        day += timedelta(days=1)
    return times


def _report_urls(issued_at: datetime) -> tuple[str, str]:
    """Return the archive URLs of an issuance's Forecast Discussion and 3-Day Forecast reports.

    Args:
        issued_at: The issuance timestamp.

    Returns:
        The ``(discussion_url, forecast_url)`` pair.
    """
    stamp = issued_at.strftime("%Y%m%d%H%M")
    year, month = issued_at.strftime("%Y"), issued_at.strftime("%m")
    return (
        f"{_DISCUSSION_BASE}/{year}/{month}/{stamp}forecast_discussion.txt",
        f"{_FORECAST_BASE}/{year}/{month}/{stamp}three_day_forecast.txt",
    )


async def _fetch_issuance(client: httpx.AsyncClient, issued_at: datetime, cache_dir: Path) -> _Issuance | None:
    """Fetch one issuance's two reports, or return ``None`` if NOAA's archive has no such issuance.

    NOAA's discussion archive has observed gaps (for example, missing issuances early in a
    product's life). A 404 for either report means the issuance was never published, which this
    function treats as absent rather than as a download failure. Any other HTTP error propagates.

    Args:
        client: The shared HTTP client.
        issued_at: The issuance timestamp to fetch.
        cache_dir: Directory to cache the two report files in.

    Returns:
        The issuance, or ``None`` if NOAA's archive has no report for this timestamp.
    """
    stamp = issued_at.strftime("%Y%m%d%H%M")
    discussion_url, forecast_url = _report_urls(issued_at)
    discussion_path = cache_dir / "discussion" / f"{stamp}.txt"
    forecast_path = cache_dir / "forecast" / f"{stamp}.txt"
    for url, dest in ((discussion_url, discussion_path), (forecast_url, forecast_path)):
        if dest.exists():
            continue
        response = await client.get(url)
        if response.status_code == httpx.codes.NOT_FOUND:
            return None
        response.raise_for_status()
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(response.content)
    return _Issuance(issued_at=issued_at, discussion_path=discussion_path, forecast_path=forecast_path)


class SpaceWeatherCotConnector(BaseConnector[SpaceWeatherRaw]):
    """Connector for SpaceWeather-CoT (NOAA SWPC Forecast Discussions + GOES X-ray + OMNI2)."""

    @staticmethod
    async def download_async(cache_dir: Path) -> SpaceWeatherRaw:
        """Fetch the pinned GOES/OMNI2 archives and every issuance's two report texts.

        Args:
            cache_dir: The directory that holds downloaded files.

        Returns:
            The :class:`SpaceWeatherRaw` handle.

        Raises:
            TimeNetConnectorError: If NOAA's archive has no issuance in the configured date range.
        """
        xray_path = cache_dir / "goes16_xrs_2024.nc"
        omni_path = cache_dir / "omni2_2024.dat"
        await download_files(
            [
                Artifact(_GOES_XRS_URL, xray_path, sha256=_GOES_XRS_SHA256),
                Artifact(_OMNI2_URL, omni_path, sha256=_OMNI2_SHA256),
            ]
        )
        semaphore = asyncio.Semaphore(8)
        async with httpx.AsyncClient(timeout=httpx.Timeout(60.0), follow_redirects=True) as client:

            async def bounded(issued_at: datetime) -> _Issuance | None:
                async with semaphore:
                    return await _fetch_issuance(client, issued_at, cache_dir)

            results = await asyncio.gather(*(bounded(t) for t in _issuance_times()))
        issuances = tuple(issuance for issuance in results if issuance is not None)
        if not issuances:
            raise TimeNetConnectorError(f"no Forecast Discussion issuances found between {_START_DATE} and {_END_DATE}")
        return SpaceWeatherRaw(issuances=issuances, xray_path=xray_path, omni_path=omni_path)

    def convert(self, raw: SpaceWeatherRaw) -> TimeFDataset:
        """Build one record and task set per successfully fetched issuance.

        Args:
            raw: The handle from :meth:`download_async`.

        Returns:
            The populated :class:`~timenet.dataset.TimeFDataset`.

        Raises:
            TimeNetConnectorError: If a report's text does not match the expected four-section
                Forecast Discussion shape, or the 3-Day Forecast text is missing an expected
                numeric field.
        """
        xray = _read_goes_xray(raw.xray_path)
        omni = _read_omni2(raw.omni_path)
        dataset = TimeFDataset(metadata=self.metadata())
        for issuance in raw.issuances:
            try:
                self._add_issuance(dataset, issuance, xray, omni)
            except (ValueError, KeyError) as exc:
                raise TimeNetConnectorError(
                    f"invalid SpaceWeather-CoT issuance {issuance.issued_at.isoformat()}: {exc}"
                ) from exc
        return dataset

    @staticmethod
    def _add_issuance(
        dataset: TimeFDataset,
        issuance: _Issuance,
        xray: "_GoesXray",
        omni: "_Omni2",
    ) -> None:
        """Add one issuance's record, answer task, and scalar-prediction tasks to ``dataset``."""
        window_start = issuance.issued_at - _LOOKBACK
        xray_times, xray_values = xray.window(window_start, issuance.issued_at)
        omni_times, omni_fields = omni.window(window_start, issuance.issued_at)
        if xray_times.size == 0 or not omni_times:
            raise ValueError("no GOES or OMNI2 samples fall in this issuance's 24-hour lookback window")

        xray_moments = [moment.replace(tzinfo=UTC) for moment in xray_times.astype("datetime64[us]").astype(object)]
        xray_offsets = time_offsets_from_datetimes(xray_moments, start_time=window_start)
        omni_offsets = time_offsets_from_datetimes(omni_times, start_time=window_start)
        signals = [
            Signal.from_irregular(xray_values, time_offsets_us=xray_offsets, spec=_XRAY_SPEC, name="xrsb_flux"),
            Signal.from_irregular(omni_fields["bz_gsm"], time_offsets_us=omni_offsets, spec=_BZ_SPEC, name="bz_gsm"),
            Signal.from_irregular(omni_fields["speed"], time_offsets_us=omni_offsets, spec=_SPEED_SPEC, name="speed"),
            Signal.from_irregular(
                omni_fields["density"], time_offsets_us=omni_offsets, spec=_DENSITY_SPEC, name="density"
            ),
            Signal.from_irregular(omni_fields["kp"], time_offsets_us=omni_offsets, spec=_KP_SPEC, name="kp"),
        ]
        record = Record(
            sources=[Source("space weather", signals=signals)],
            annotations=[
                Annotation("issued_at", value=issuance.issued_at.isoformat()),
                Annotation("satellite", value="GOES-16"),
            ],
        )
        dataset.add_record(record)

        summary_text, forecast_text = _parse_discussion(issuance.discussion_path.read_text())
        dataset.add_task(AnswerTask(inputs=[record], prompt=_PROMPT, rationale=summary_text, targets=forecast_text))
        numeric = _parse_three_day_forecast(issuance.forecast_path.read_text())
        dataset.add_tasks(
            [
                ScalarPredictionTask(
                    inputs=[record],
                    targets=numeric["kp_max_3day"],
                    target_name="kp_max_3day",
                    unit="dimensionless",
                ),
                ScalarPredictionTask(
                    inputs=[record],
                    targets=numeric["r1_r2_pct_day1"],
                    target_name="r1_r2_radio_blackout_pct",
                    unit="percent",
                ),
                ScalarPredictionTask(
                    inputs=[record],
                    targets=numeric["s1_pct_day1"],
                    target_name="s1_radiation_storm_pct",
                    unit="percent",
                ),
            ]
        )


def _parse_discussion(text: str) -> tuple[str, str]:
    """Split a Forecast Discussion's four sections into a joined summary and a joined forecast.

    Args:
        text: The raw Forecast Discussion report text.

    Returns:
        ``(summary_text, forecast_text)``, each the four sections' matching subsection joined with
        its section name.

    Raises:
        TimeNetConnectorError: If the text does not have exactly the four expected section headers.
    """
    headers = list(_SECTION_HEADER.finditer(text))
    names = ["Energetic Particle" if h.group(1) == "Energetic Particles" else h.group(1) for h in headers]
    if names != list(_SECTIONS):
        raise TimeNetConnectorError(f"expected section headers {list(_SECTIONS)} in order, found {names}")
    summaries, forecasts = [], []
    for index, header in enumerate(headers):
        start = header.end()
        end = headers[index + 1].start() if index + 1 < len(headers) else len(text)
        block = text[start:end]
        forecast_split = _FORECAST_MARKER.split(block, maxsplit=1)
        summary_part = _SUMMARY_MARKER.sub("", forecast_split[0], count=1)
        forecast_part = forecast_split[1] if len(forecast_split) > 1 else ""
        summaries.append(f"{_SECTIONS[index]}: {summary_part.strip()}")
        forecasts.append(f"{_SECTIONS[index]}: {forecast_part.strip()}")
    return "\n\n".join(summaries), "\n\n".join(forecasts)


def _parse_three_day_forecast(text: str) -> dict[str, float]:
    """Extract NOAA's own numeric 3-day forecast fields.

    Args:
        text: The raw 3-Day Forecast report text.

    Returns:
        ``kp_max_3day`` (the greatest expected 3-hour Kp over the next 3 days), ``r1_r2_pct_day1``
        and ``s1_pct_day1`` (the first forecast day's R1-R2 radio-blackout and S1 radiation-storm
        percentages).

    Raises:
        TimeNetConnectorError: If any of the three fields cannot be found.
    """
    kp_match, r1r2_match, s1_match = _KP_RE.search(text), _R1R2_RE.search(text), _S1_RE.search(text)
    if not (kp_match and r1r2_match and s1_match):
        raise TimeNetConnectorError("could not find the expected numeric fields in a 3-Day Forecast report")
    return {
        "kp_max_3day": float(kp_match.group(1)),
        "r1_r2_pct_day1": float(r1r2_match.group(1)),
        "s1_pct_day1": float(s1_match.group(1)),
    }


# --- GOES X-ray reading ---------------------------------------------------------------------------

_GOES_EPOCH = datetime(2000, 1, 1, 12, tzinfo=UTC)


@dataclass(frozen=True)
class _GoesXray:
    """GOES-16 XRS-B (0.1-0.8 nm) flux, electron-corrected, with bad samples nulled out."""

    times: np.ndarray  # datetime64[us], ascending
    values: np.ndarray  # float32, NaN where flagged or missing

    def window(self, start: datetime, end: datetime) -> tuple[np.ndarray, list[float | None]]:
        """Return the samples in ``[start, end)``, as (datetime64 array, values with NaN -> None)."""
        lo = np.searchsorted(self.times, np.datetime64(start.replace(tzinfo=None)), side="left")
        hi = np.searchsorted(self.times, np.datetime64(end.replace(tzinfo=None)), side="left")
        values = self.values[lo:hi]
        return self.times[lo:hi], [None if np.isnan(value) else float(value) for value in values]


def _read_goes_xray(path: Path) -> _GoesXray:
    """Read GOES-16 XRS-B flux from an ``xrsf-l2-avg1m_science`` NetCDF file.

    Args:
        path: Path to the downloaded science NetCDF file.

    Returns:
        The flux series, sorted by time, with flagged or non-finite samples set to NaN.

    Raises:
        ImportError: If the ``netCDF4`` package is not installed.
    """
    try:
        import netCDF4  # ruff: ignore[import-outside-top-level] (lazy: optional dep, see requirements.txt)
    except ImportError as exc:
        raise ImportError(
            "the noaa/spaceweather-cot connector needs the 'netCDF4' package; install it from "
            "this connector's requirements.txt"
        ) from exc
    with netCDF4.Dataset(path) as dataset:
        seconds = np.asarray(dataset.variables["time"][:], dtype="float64")
        flux = np.asarray(dataset.variables["xrsb_flux"][:], dtype="float32")
        flag = np.asarray(dataset.variables["xrsb_flag"][:])
    times = (np.datetime64(_GOES_EPOCH.replace(tzinfo=None)) + (seconds * 1_000_000).astype("int64")).astype(
        "datetime64[us]"
    )
    flux = np.where(flag == 0, flux, np.nan).astype("float32")
    return _GoesXray(times=times, values=flux)


# --- OMNI2 reading ---------------------------------------------------------------------------------

# Column indices (0-based) into a whitespace-split OMNI2_YYYY.DAT row, and each column's fill value.
# See https://spdf.gsfc.nasa.gov/pub/data/omni/low_res_omni/omni2.text for the full format.
_OMNI_BZ_GSM_COL, _OMNI_BZ_GSM_FILL = 16, 999.9
_OMNI_DENSITY_COL, _OMNI_DENSITY_FILL = 23, 999.9
_OMNI_SPEED_COL, _OMNI_SPEED_FILL = 24, 9999.0
_OMNI_KP_COL = 38  # I3 code: tens digit is the Kp level, ones digit is {0: "o", 3: "+", 7: "-"} a third.
_OMNI_KP_THIRDS = {0: 0.0, 3: 1 / 3, 7: -1 / 3}


@dataclass(frozen=True)
class _Omni2:
    """OMNI2 hourly solar-wind and Kp values, keyed by their hour (naive UTC)."""

    rows: dict[datetime, dict[str, float | None]]

    def window(self, start: datetime, end: datetime) -> tuple[list[datetime], dict[str, list[float | None]]]:
        """Return the hourly timestamps and field values in ``[start, end)``.

        Args:
            start: Window start, inclusive.
            end: Window end, exclusive.

        Returns:
            The timestamps (tz-aware UTC) and a ``{field: values}`` mapping, aligned to them.
            An hour this dataset has no row for is skipped rather than filled in.
        """
        naive_start, naive_end = start.replace(tzinfo=None), end.replace(tzinfo=None)
        hour = naive_start.replace(minute=0, second=0, microsecond=0)
        if hour < naive_start:  # round up to the first hour at or after start, never before it
            hour += timedelta(hours=1)
        times, fields = [], {"bz_gsm": [], "speed": [], "density": [], "kp": []}
        while hour < naive_end:
            if (row := self.rows.get(hour)) is not None:
                times.append(hour.replace(tzinfo=UTC))
                for key, values in fields.items():
                    values.append(row[key])
            hour += timedelta(hours=1)
        return times, fields


def _decode_omni_kp(code: int) -> float:
    """Decode an OMNI2 Kp code (for example ``33`` -> ``3+`` -> ``3.333``) to a float."""
    tens, ones = divmod(code, 10)
    return tens + _OMNI_KP_THIRDS[ones]


def _read_omni2(path: Path) -> _Omni2:
    """Read hourly Bz (GSM), solar-wind speed, proton density, and Kp from an OMNI2 yearly file.

    Args:
        path: Path to the downloaded ``omni2_YYYY.dat`` file.

    Returns:
        The parsed rows, keyed by hour.
    """
    rows: dict[datetime, dict[str, float | None]] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        fields = line.split()
        year, day_of_year, hour = int(fields[0]), int(fields[1]), int(fields[2])
        moment = datetime(year, 1, 1) + timedelta(days=day_of_year - 1, hours=hour)
        bz = float(fields[_OMNI_BZ_GSM_COL])
        speed = float(fields[_OMNI_SPEED_COL])
        density = float(fields[_OMNI_DENSITY_COL])
        rows[moment] = {
            "bz_gsm": None if bz == _OMNI_BZ_GSM_FILL else bz,
            "speed": None if speed == _OMNI_SPEED_FILL else speed,
            "density": None if density == _OMNI_DENSITY_FILL else density,
            "kp": _decode_omni_kp(int(fields[_OMNI_KP_COL])),
        }
    return _Omni2(rows=rows)


